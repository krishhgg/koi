import { PreviewLabelSchema } from '@koi/shared';
import { writeFileAtomic } from './fsutil.ts';

export interface Route {
	label: string;
	// ip:port of the preview container on the preview network.
	upstream: string;
}

// How Caddy gets certificates for *.<domain> (KOI_TLS, config.ts).
// route53: one wildcard certificate over DNS-01 with the AWS box's role.
// internal: one wildcard certificate from Caddy's own CA, which the machines
// that visit must trust; for a local host or a network of one's own.
// acme-http: a certificate per preview name from the default ACME issuers
// over HTTP-01 or TLS-ALPN-01, which cannot issue a wildcard; Caddy gets one
// at the first visit of a name, once koid's ask endpoint says the name is a
// preview's (server.ts). acme-dns: one wildcard certificate over DNS-01 with
// a caddy-dns provider, whose `dns` line lives in `file`, root's and Caddy's,
// so that koid never sees its credentials.
export type CaddyTls =
	| { kind: 'route53' }
	| { kind: 'internal' }
	| { kind: 'acme-http' }
	| { kind: 'acme-dns'; file: string };

export interface CaddyfileOptions {
	domain: string;
	httpPort: number;
	logPort: number;
	routes: Route[];
	// Route 53 unless given, as on the AWS box.
	tls?: CaddyTls | undefined;
	// The unix socket Caddy's admin API listens on, mode 0660 in Caddy's
	// group, which koid's account is in (host/cloud-init.sh). Unless given,
	// 127.0.0.1:2019, as on the AWS box, which has no account but its own.
	// On a host with other accounts any of them could reach that port and
	// change what Caddy serves, or have it answer with its environment.
	adminSocket?: string | undefined;
}

// The path Caddy asks before it gets a certificate for a name on demand.
export const TLS_ASK_PATH = '/__koi/tls-ask';

// A path that is one Caddyfile token: Caddy reads it back as the same path.
const TOKEN_PATH = /^\/[A-Za-z0-9._/-]+$/;

const UPSTREAM = /^(?:\d{1,3}\.){3}\d{1,3}:\d{1,5}$/;

// The whole Caddy configuration, regenerated on every change. Labels and
// upstreams are validated here because they are written into the file.
//
// Order matters: /__koi/* always reaches koid (health checks, never the
// preview); each running preview's host goes to its container; anything else
// goes to koid, which explains why there is nothing there. When a preview's
// container cannot be reached, handle_errors hands the request to koid, which
// starts the container and shows a waiting page. If koid is down too, Caddy
// answers 502 and CloudFront shows the wake page.
//
// The keys page limits registrations by the viewer's address (keys.ts,
// viewerSource), which koid reads from X-Koi-Forwarded-For; Caddy sets it, so
// a client cannot supply its own. On the AWS box Caddy's peer is a CloudFront
// server, so the header is the X-Forwarded-For CloudFront sent, with the
// viewer's address appended last, or empty if there was none. Elsewhere
// nothing stands in front of Caddy and a client could write X-Forwarded-For
// itself, so the header is Caddy's peer's address.
//
// Every route change loads the whole file again, and by default a reload
// closes proxied streams such as an app's WebSocket. stream_close_delay
// keeps them open on the old config for up to 8 hours instead:
// https://caddyserver.com/docs/caddyfile/directives/reverse_proxy#streaming
export function renderCaddyfile(options: CaddyfileOptions): string {
	const koid = `127.0.0.1:${options.httpPort}`;
	const routes = [...options.routes].sort((a, b) => a.label.localeCompare(b.label));
	const blocks = routes.map((route, i) => {
		PreviewLabelSchema.parse(route.label);
		if (!UPSTREAM.test(route.upstream)) {
			throw new Error(`bad upstream ${JSON.stringify(route.upstream)} for ${route.label}`);
		}
		return `	@p${i} host ${route.label}.${options.domain}
	handle @p${i} {
		reverse_proxy ${route.upstream} {
			flush_interval -1
			stream_close_delay 8h
		}
	}
`;
	});
	const tls = options.tls ?? { kind: 'route53' };
	if (options.adminSocket !== undefined && !TOKEN_PATH.test(options.adminSocket)) {
		throw new Error(`bad admin socket ${JSON.stringify(options.adminSocket)}`);
	}
	const admin =
		options.adminSocket === undefined ? '127.0.0.1:2019' : `unix/${options.adminSocket}|0660`;
	const viewer =
		tls.kind === 'route53' ? '{http.request.header.X-Forwarded-For}' : '{http.request.remote.host}';
	// On demand, Caddy asks koid directly, never through itself. With its own
	// CA, Caddy would try to add the CA's root to the system's trust store
	// at start, through sudo as the caddy account; the operator does that
	// once with caddy trust instead (docs/configuration.md).
	const global =
		tls.kind === 'acme-http'
			? `	on_demand_tls {
		ask http://${koid}${TLS_ASK_PATH}
	}
`
			: tls.kind === 'internal'
				? '\tskip_install_trust\n'
				: '';
	return `# Generated by koid; rewritten on every change. Edits here are lost.
{
	auto_https disable_redirects
	admin ${admin}
${global}}

*.${options.domain} {
${tlsBlock(tls)}	log {
		output net 127.0.0.1:${options.logPort} {
			soft_start
		}
		format json
	}

${tls.kind === 'acme-http' ? ASK_CLOSED : ''}	handle /__koi/* {
		reverse_proxy ${koid}
	}

${blocks.join('\n')}
	handle {
		reverse_proxy ${koid} {
			header_up X-Koi-Forwarded-For ${viewer}
		}
	}

	handle_errors 502 503 504 {
		reverse_proxy ${koid} {
			header_up X-Koi-Error {http.error.status_code}
		}
	}
}
`;
}

// Caddy's question to koid before a certificate on demand is for Caddy
// alone: a visitor gets nothing at that path, whatever the host.
const ASK_CLOSED = `	handle ${TLS_ASK_PATH} {
		respond 404
	}

`;

function tlsBlock(tls: CaddyTls): string {
	switch (tls.kind) {
		case 'route53':
			return `	tls {
		dns route53 {
			wait_for_route53_sync true
			route53_max_wait 2m
		}
		propagation_delay 30s
	}
`;
		case 'internal':
			return '\ttls internal\n';
		case 'acme-http':
			return '\ttls {\n\t\ton_demand\n\t}\n';
		case 'acme-dns':
			if (!TOKEN_PATH.test(tls.file)) {
				throw new Error(`bad DNS provider file ${JSON.stringify(tls.file)}`);
			}
			return `\ttls {\n\t\timport ${tls.file}\n\t}\n`;
	}
}

export interface CaddyApplier {
	apply(routes: Route[]): Promise<void>;
}

// Loads the config through the admin API, saves the same text to the file
// Caddy reads when it starts, then loads it again. The file only ever holds
// a config Caddy accepted. The second load covers a Caddy restart between
// the first load and the save: that Caddy started from the file as it was,
// so it may run the old config, and only a load after the save makes what
// it runs and the file agree. Caddy answers a load of the config it already
// runs without reloading. Skips all three when the text is what Caddy last
// accepted.
//
// While an apply is in flight, and after one fails, what Caddy runs is
// unknown: a timeout can come after Caddy took the config, and a restart can
// undo a load it answered. `last` is cleared for that time and set only once
// the second load is accepted, so the next apply sends its config even if
// the text is the same.
//
// `adminUrl` is an http URL, or unix//PATH for the admin API on a unix
// socket (config.ts), which the config names as Caddy's admin address too.
// Over a socket Caddy takes any Host header.
export function caddyApplier(options: {
	domain: string;
	httpPort: number;
	logPort: number;
	tls?: CaddyTls | undefined;
	file: string;
	adminUrl: string;
	fetch?: typeof fetch;
}): CaddyApplier {
	let last: string | undefined;
	const doFetch = options.fetch ?? fetch;
	const adminSocket = options.adminUrl.startsWith('unix/')
		? options.adminUrl.slice('unix/'.length)
		: undefined;
	const load = async (text: string) => {
		const init = {
			method: 'POST',
			headers: { 'content-type': 'text/caddyfile' },
			body: text,
			signal: AbortSignal.timeout(30_000),
		};
		const res =
			adminSocket === undefined
				? await doFetch(new URL('/load', options.adminUrl), init)
				: await doFetch(new URL('http://localhost/load'), {
						...init,
						unix: adminSocket,
					} as RequestInit);
		if (!res.ok) {
			// A DNS provider's module may quote its API key in the error, as
			// caddy-dns/cloudflare does for one it finds malformed, and koid's
			// errors reach koi's users. Caddy logs the whole error itself.
			const why =
				options.tls?.kind === 'acme-dns'
					? "(the reason is in Caddy's log: journalctl -u caddy)"
					: (await res.text()).slice(0, 500);
			throw new Error(`caddy rejected the config: ${res.status} ${why}`);
		}
	};
	return {
		async apply(routes) {
			const text = renderCaddyfile({
				domain: options.domain,
				httpPort: options.httpPort,
				logPort: options.logPort,
				tls: options.tls,
				adminSocket,
				routes,
			});
			if (text === last) return;
			last = undefined;
			await load(text);
			await writeFileAtomic(options.file, text);
			await load(text);
			last = text;
		},
	};
}
