import { PreviewLabelSchema } from '@koi/shared';
import { writeFileAtomic } from './fsutil.ts';

export interface Route {
	label: string;
	// ip:port of the preview container on the preview network.
	upstream: string;
}

export interface CaddyfileOptions {
	domain: string;
	httpPort: number;
	logPort: number;
	routes: Route[];
}

const UPSTREAM = /^(?:\d{1,3}\.){3}\d{1,3}:\d{1,5}$/;

// The whole Caddy configuration, regenerated on every change. Labels and
// upstreams are validated here because they are written into the file.
//
// Order matters: /__koi/* always reaches koid (health checks, never the
// preview); each running preview's host goes to its container; anything else
// goes to koid, which explains why there is nothing there. When a preview's
// container cannot be reached, handle_errors hands the request to koid, which
// starts the container and shows a waiting page. If koid is down too, Caddy
// answers 502 and CloudFront shows the wake page.
//
// The keys page limits registrations by the viewer's address (keys.ts,
// viewerSource). Caddy trusts no proxy, so it replaces X-Forwarded-For with
// its peer's address, a CloudFront server's. The X-Forwarded-For CloudFront
// sent, with the viewer's address appended last, goes to koid as
// X-Koi-Forwarded-For instead; Caddy sets it, empty if there was none, so a
// client cannot supply its own.
//
// Every route change loads the whole file again, and by default a reload
// closes proxied streams such as an app's WebSocket. stream_close_delay
// keeps them open on the old config for up to 8 hours instead:
// https://caddyserver.com/docs/caddyfile/directives/reverse_proxy#streaming
export function renderCaddyfile(options: CaddyfileOptions): string {
	const koid = `127.0.0.1:${options.httpPort}`;
	const routes = [...options.routes].sort((a, b) => a.label.localeCompare(b.label));
	const blocks = routes.map((route, i) => {
		PreviewLabelSchema.parse(route.label);
		if (!UPSTREAM.test(route.upstream)) {
			throw new Error(`bad upstream ${JSON.stringify(route.upstream)} for ${route.label}`);
		}
		return `	@p${i} host ${route.label}.${options.domain}
	handle @p${i} {
		reverse_proxy ${route.upstream} {
			flush_interval -1
			stream_close_delay 8h
		}
	}
`;
	});
	return `# Generated by koid; rewritten on every change. Edits here are lost.
{
	auto_https disable_redirects
	admin 127.0.0.1:2019
}

*.${options.domain} {
	tls {
		dns route53 {
			wait_for_route53_sync true
			route53_max_wait 2m
		}
		propagation_delay 30s
	}
	log {
		output net 127.0.0.1:${options.logPort} {
			soft_start
		}
		format json
	}

	handle /__koi/* {
		reverse_proxy ${koid}
	}

${blocks.join('\n')}
	handle {
		reverse_proxy ${koid} {
			header_up X-Koi-Forwarded-For {http.request.header.X-Forwarded-For}
		}
	}

	handle_errors 502 503 504 {
		reverse_proxy ${koid} {
			header_up X-Koi-Error {http.error.status_code}
		}
	}
}
`;
}

export interface CaddyApplier {
	apply(routes: Route[]): Promise<void>;
}

// Loads the config through the admin API, saves the same text to the file
// Caddy reads when it starts, then loads it again. The file only ever holds
// a config Caddy accepted. The second load covers a Caddy restart between
// the first load and the save: that Caddy started from the file as it was,
// so it may run the old config, and only a load after the save makes what
// it runs and the file agree. Caddy answers a load of the config it already
// runs without reloading. Skips all three when the text is what Caddy last
// accepted.
//
// While an apply is in flight, and after one fails, what Caddy runs is
// unknown: a timeout can come after Caddy took the config, and a restart can
// undo a load it answered. `last` is cleared for that time and set only once
// the second load is accepted, so the next apply sends its config even if
// the text is the same.
export function caddyApplier(options: {
	domain: string;
	httpPort: number;
	logPort: number;
	file: string;
	adminUrl: string;
	fetch?: typeof fetch;
}): CaddyApplier {
	let last: string | undefined;
	const doFetch = options.fetch ?? fetch;
	const load = async (text: string) => {
		const res = await doFetch(new URL('/load', options.adminUrl), {
			method: 'POST',
			headers: { 'content-type': 'text/caddyfile' },
			body: text,
			signal: AbortSignal.timeout(30_000),
		});
		if (!res.ok) {
			throw new Error(
				`caddy rejected the config: ${res.status} ${(await res.text()).slice(0, 500)}`,
			);
		}
	};
	return {
		async apply(routes) {
			const text = renderCaddyfile({
				domain: options.domain,
				httpPort: options.httpPort,
				logPort: options.logPort,
				routes,
			});
			if (text === last) return;
			last = undefined;
			await load(text);
			await writeFileAtomic(options.file, text);
			await load(text);
			last = text;
		},
	};
}
